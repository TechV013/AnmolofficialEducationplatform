#!/usr/bin/env node
/**
 * Provision the accounts and fixtures the Playwright smoke suite needs.
 *
 * Usage:
 *   npm run e2e:provision -- --dry-run     # print the plan, write nothing
 *   npm run e2e:provision -- --yes         # apply
 *
 * Everything it creates is namespaced to `e2e.*@anmolofficial.com` plus one
 * dedicated draft course, so no real user's data is modified. Re-running is
 * safe: every write is an upsert keyed on a unique column.
 *
 * Passwords are generated once and stored in `.env.e2e.local` (git-ignored).
 * They are never printed, logged, or committed.
 */
import { PrismaClient } from "@prisma/client";
import bcrypt from "bcryptjs";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const BCRYPT_ROUNDS = 12;
const ROOT = process.cwd();
const LOCAL_ENV = path.join(ROOT, ".env.e2e.local");

const E2E_COURSE_SLUG = "e2e-smoke-test-course";

const ACCOUNTS = [
  { role: "STUDENT", name: "E2E Student", key: "STUDENT" },
  { role: "INSTRUCTOR", name: "E2E Instructor", key: "INSTRUCTOR" },
  { role: "ADMIN", name: "E2E Admin", key: "ADMIN" }
];

function loadEnvFile(file) {
  if (!fs.existsSync(file)) return;
  for (const raw of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

loadEnvFile(path.join(ROOT, ".env"));
loadEnvFile(LOCAL_ENV);

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const confirmed = args.includes("--yes");

if (!process.env.DATABASE_URL) {
  console.error("DATABASE_URL is not set. Add it to .env before provisioning.");
  process.exit(1);
}

function generatePassword() {
  return `E2e-${crypto.randomBytes(16).toString("base64url")}-7a`;
}

/**
 * Ensures every E2E_* credential exists in .env.e2e.local. Returns the values to
 * use; missing passwords are generated here so they never travel through argv,
 * the shell, or the console.
 */
function ensureCredentials() {
  const resolved = {};
  const lines = [];

  if (fs.existsSync(LOCAL_ENV)) {
    lines.push(...fs.readFileSync(LOCAL_ENV, "utf8").split(/\r?\n/).filter(Boolean));
  }

  const existing = new Map();
  for (const line of lines) {
    if (line.trim().startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq < 0) continue;
    existing.set(line.slice(0, eq).trim(), line.slice(eq + 1).trim());
  }

  for (const account of ACCOUNTS) {
    const emailKey = `E2E_${account.key}_EMAIL`;
    const passwordKey = `E2E_${account.key}_PASSWORD`;
    const email = existing.get(emailKey) ?? process.env[emailKey] ?? `e2e.${account.key.toLowerCase()}@anmolofficial.com`;
    const password = existing.get(passwordKey) ?? process.env[passwordKey] ?? generatePassword();

    existing.set(emailKey, email);
    existing.set(passwordKey, password);
    resolved[account.key] = { email, password, role: account.role, name: account.name };
  }

  if (!dryRun) {
    const header = "# Generated by scripts/provision-e2e-accounts.mjs - git-ignored, do not commit.";
    const body = Array.from(existing.entries())
      .map(([key, value]) => `${key}=${value}`)
      .join("\n");
    fs.writeFileSync(LOCAL_ENV, `${header}\n${body}\n`, "utf8");

    // Fail loudly rather than letting the suite silently fall back to the demo
    // accounts, which is what a malformed file previously caused.
    const written = new Map();
    for (const line of fs.readFileSync(LOCAL_ENV, "utf8").split(/\r?\n/)) {
      const eq = line.indexOf("=");
      if (eq > 0) written.set(line.slice(0, eq).trim(), line.slice(eq + 1).trim());
    }
    const broken = ACCOUNTS.filter(
      (account) => !written.get(`E2E_${account.key}_EMAIL`) || !written.get(`E2E_${account.key}_PASSWORD`)
    );
    if (broken.length > 0) {
      throw new Error(
        `${LOCAL_ENV} is malformed; missing credentials for: ${broken.map((a) => a.key).join(", ")}`
      );
    }
  }

  return resolved;
}

const prisma = new PrismaClient();

async function plan() {
  const steps = [];

  steps.push("upsert 3 E2E accounts (STUDENT, INSTRUCTOR, ADMIN)");
  steps.push(`create or reuse draft course "${E2E_COURSE_SLUG}" with 1 module + 1 lesson`);
  steps.push("assign the E2E instructor to that course (CourseInstructor)");
  steps.push("enroll the E2E student in one existing PUBLISHED course that has lessons");

  const target = await prisma.course.findFirst({
    where: { status: "PUBLISHED", modules: { some: { lessons: { some: {} } } } },
    orderBy: { createdAt: "asc" },
    select: { id: true, title: true }
  });

  if (!target) {
    console.warn("No PUBLISHED course with lessons exists; the student classroom journeys will stay skipped.");
  }

  return { steps, target };
}

async function apply() {
  const credentials = ensureCredentials();

  const users = {};
  for (const account of ACCOUNTS) {
    const { email, password, role, name } = credentials[account.key];
    const passwordHash = await bcrypt.hash(password, BCRYPT_ROUNDS);
    const user = await prisma.user.upsert({
      where: { email },
      update: { name, role, passwordHash, isActive: true },
      create: { email, name, role, passwordHash, isActive: true }
    });
    users[account.key] = user;
    console.log(`account ready: ${email} (${user.role}, active=${user.isActive})`);
  }

  const price = (await import("@prisma/client/runtime/library")).Decimal;

  const course = await prisma.course.upsert({
    where: { slug: E2E_COURSE_SLUG },
    update: {},
    create: {
      title: "E2E Smoke Test Course",
      slug: E2E_COURSE_SLUG,
      description: "Fixture course owned by the E2E instructor account. Safe to edit.",
      category: "E2E",
      level: "Beginner",
      thumbnail: "/images/demo-course-1.jpg",
      price: new price("0"),
      status: "DRAFT"
    }
  });
  console.log(`course ready: ${course.title} (${course.slug}, ${course.status})`);

  const existingModule = await prisma.module.findFirst({
    where: { courseId: course.id },
    orderBy: { position: "asc" }
  });

  const courseModule =
    existingModule ??
    (await prisma.module.create({ data: { courseId: course.id, title: "E2E Module", position: 0 } }));
  console.log(`module ready: ${courseModule.title}`);

  const existingLesson = await prisma.lesson.findFirst({
    where: { moduleId: courseModule.id },
    orderBy: { position: "asc" }
  });

  if (!existingLesson) {
    const lesson = await prisma.lesson.create({
      data: {
        moduleId: courseModule.id,
        title: "E2E Lesson",
        description: "Fixture lesson for Course Studio smoke tests.",
        position: 0,
        duration: "5 min",
        published: true
      }
    });
    console.log(`lesson ready: ${lesson.title}`);
  } else {
    console.log(`lesson ready: ${existingLesson.title}`);
  }

  await prisma.courseInstructor.upsert({
    where: { courseId_userId: { courseId: course.id, userId: users.INSTRUCTOR.id } },
    update: {},
    create: { courseId: course.id, userId: users.INSTRUCTOR.id }
  });
  console.log("instructor assigned to the E2E course");

  const target = await prisma.course.findFirst({
    where: {
      id: { not: course.id },
      status: "PUBLISHED",
      modules: { some: { lessons: { some: {} } } }
    },
    orderBy: { createdAt: "asc" },
    select: { id: true, title: true }
  });

  if (target) {
    const enrollment = await prisma.enrollment.upsert({
      where: { userId_courseId: { userId: users.STUDENT.id, courseId: target.id } },
      update: { status: "ACTIVE" },
      create: { userId: users.STUDENT.id, courseId: target.id, status: "ACTIVE" }
    });
    console.log(`student enrolled (ACTIVE) in: ${target.title} [${enrollment.id}]`);
  } else {
    console.warn("No PUBLISHED course with lessons found; student classroom journeys stay skipped.");
  }

  console.log("\nCredentials stored in .env.e2e.local (not printed). Re-run: npm run e2e:provision -- --yes");
}

try {
  if (dryRun) {
    const { steps, target } = await plan();
    console.log("DRY RUN - nothing will be written\n");
    steps.forEach((step, index) => console.log(`${index + 1}. ${step}`));
    console.log(`\nstudent enrollment target: ${target ? target.title : "(none found)"}`);
    console.log(`\ndatabase fingerprint: ${new URL(process.env.DATABASE_URL).hostname}`);
  } else {
    if (!confirmed) {
      console.error("Refusing to write without --yes. Re-run with --yes, or --dry-run to preview.");
      process.exit(1);
    }
    await apply();
  }
} finally {
  await prisma.$disconnect();
}